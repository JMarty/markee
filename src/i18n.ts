const dicts: Record<Lang, Dict> = { en, hu, de, es };

type StringKey = { [K in keyof Dict]: Dict[K] extends string ? K : never }[keyof Dict];

let current: Lang = "en";

export function detectLang(): Lang {
  for (const l of navigator.languages ?? [navigator.language]) {
    const code = l.slice(0, 2).toLowerCase();
    if (code in dicts) return code as Lang;
  }
  return "en";
}

export function setLang(l: Lang) {
  current = l;
  document.documentElement.lang = l;
  applyI18n();
}

export const getLang = () => current;

export function t(key: StringKey, ...args: (string | number)[]): string {
  const s = (dicts[current][key] ?? en[key]) as string;
  return args.length ? s.replace(/\{(\d)\}/g, (_, i) => String(args[+i] ?? "")) : s;
}

export const tips = (): string[] => dicts[current].tips;

/** `data-i18n` → szöveg, `data-i18n-title` → title, `data-i18n-ph` → placeholder. */
export function applyI18n(root: ParentNode = document) {
  for (const el of root.querySelectorAll<HTMLElement>("[data-i18n]")) el.textContent = t(el.dataset.i18n as StringKey);
  for (const el of root.querySelectorAll<HTMLElement>("[data-i18n-title]"))
    el.title = t(el.dataset.i18nTitle as StringKey);
  for (const el of root.querySelectorAll<HTMLInputElement>("[data-i18n-ph]"))
    el.placeholder = t(el.dataset.i18nPh as StringKey);
}
